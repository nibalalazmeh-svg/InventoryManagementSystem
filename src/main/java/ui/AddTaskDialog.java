  private void loadData() {

        jComboBox1.removeAllItems();
        for (Product p : service.getAllProductDefinitions()) {
            jComboBox1.addItem(p.getName());
        }

  
        jComboBox2.removeAllItems(); 
        for (ProductionLine line : service.getAllProductionLines()) {
      
            if (line.getStatus() == model.productionLine.ProductionLineStatus.Active) {
                jComboBox2.addItem(line.getName());
            }
        }
        

        if (jComboBox1.getItemCount() == 0) {
            jComboBox1.addItem("No Products Defined!");
            jButton1.setEnabled(false); 
        }
        if (jComboBox2.getItemCount() == 0) {
            jComboBox2.addItem("No Active Lines!");
            jButton1.setEnabled(false);
        }
    }
