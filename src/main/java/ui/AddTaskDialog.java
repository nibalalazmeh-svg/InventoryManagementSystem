    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       try {
          
            String productName = (String) jComboBox1.getSelectedItem();
            String lineName = (String) jComboBox2.getSelectedItem(); 
            
            String qtyStr = jTextField2.getText();
            String client = jTextField3.getText();

            if (qtyStr.isEmpty() || client.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please fill all fields");
                return;
            }

            int quantity = Integer.parseInt(qtyStr);

          
            Product selectedProduct = null;
            for (Product p : service.getAllProductDefinitions()) {
                if (p.getName().equals(productName)) {
                    selectedProduct = p;
                    break;
                }
            }

            ProductionLine selectedLine = null;
            for (ProductionLine line : service.getAllProductionLines()) {
                if (line.getName().equals(lineName)) {
                    selectedLine = line;
                    break;
                }
            }

            if (selectedProduct == null || selectedLine == null) {
                throw new Exception("Selected Product or Line not found!");
            }

          
            boolean autoReserve = jCheckBox1.isSelected();
    
            TaskDelayOption option = jCheckBox3.isSelected() ? TaskDelayOption.CANCEL_IF_NOT_ENOUGH : TaskDelayOption.WAIT_IF_NOT_ENOUGH;

    
            Task newTask = new Task(selectedProduct, quantity, client, selectedLine, option, autoReserve, service);

    
            selectedLine.addTask(newTask);

           
            if (selectedLine.getStatus() == model.productionLine.ProductionLineStatus.Active) {
                selectedLine.startLine(); 
            }

            JOptionPane.showMessageDialog(this, "Task Assigned Successfully!");
            this.dispose();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Quantity must be a number");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    
    }//GEN-LAST:event_jButton1ActionPerformed

